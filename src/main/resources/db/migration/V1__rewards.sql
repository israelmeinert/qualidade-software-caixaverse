CREATE TABLE wallet (
    employee_id varchar(80) PRIMARY KEY,
    balance bigint NOT NULL CHECK (balance >= 0)
);

CREATE TABLE product (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku varchar(40) NOT NULL UNIQUE,
    description varchar(160) NOT NULL,
    price int NOT NULL CHECK (price > 0),
    stock int NOT NULL CHECK (stock >= 0),
    active boolean NOT NULL,
    customizable boolean NOT NULL
);

CREATE TABLE monthly_credit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id varchar(80) NOT NULL REFERENCES wallet(employee_id),
    competence varchar(7) NOT NULL CHECK (competence ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    deliveries int NOT NULL CHECK (deliveries >= 0),
    points int NOT NULL CHECK (points BETWEEN 0 AND 500),
    CONSTRAINT monthly_credit_employee_competence UNIQUE (employee_id, competence)
);

CREATE TABLE redemption (
    id uuid PRIMARY KEY,
    employee_id varchar(80) NOT NULL REFERENCES wallet(employee_id),
    idempotency_key varchar(80) NOT NULL,
    product_id bigint NOT NULL REFERENCES product(id),
    quantity int NOT NULL CHECK (quantity > 0),
    personalization varchar(40),
    unit_price int NOT NULL CHECK (unit_price > 0),
    state varchar(16) NOT NULL CHECK (state IN ('CONFIRMED')),
    CONSTRAINT redemption_employee_key UNIQUE (employee_id, idempotency_key)
);

CREATE TABLE ledger_entry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id varchar(80) NOT NULL REFERENCES wallet(employee_id),
    points bigint NOT NULL,
    monthly_credit_id bigint UNIQUE REFERENCES monthly_credit(id),
    redemption_id uuid UNIQUE REFERENCES redemption(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((monthly_credit_id IS NOT NULL AND redemption_id IS NULL AND points >= 0)
        OR (redemption_id IS NOT NULL AND monthly_credit_id IS NULL AND points < 0))
);
CREATE INDEX ledger_employee_order ON ledger_entry(employee_id, id DESC);
CREATE INDEX redemption_product ON redemption(product_id);
CREATE INDEX product_active_order ON product(id) WHERE active;
